#!/usr/bin/env node
/**
 * build-context-pack.mjs — flatten this repo into one paste-able file.
 *
 * For platforms that have no skills mechanism (ChatGPT, Gemini, a custom agent,
 * a system prompt box). Writes to stdout.
 *
 *   node tools/build-context-pack.mjs > context-pack.md          # profile + rules + skill index
 *   node tools/build-context-pack.mjs --full > context-pack.md   # + every skill body
 *   node tools/build-context-pack.mjs --only bd-import-export-domain,prove-before-claiming
 */

import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const FULL = argv.includes('--full');
const onlyArg = argv[argv.indexOf('--only') + 1];
const ONLY = argv.includes('--only') && onlyArg ? onlyArg.split(',').map(s => s.trim()) : null;

const out = [];
const say = (s = '') => out.push(s);
const read = (p) => readFileSync(join(ROOT, p), 'utf8').trim();

/* ------------------------------------------------------------------ header */

say('# Vishal Agarwal — AI context pack');
say();
say('Single-file export. Source of truth: <https://github.com/hellokianben-collab/vishal-agarwal-context>');
say(`Generated by \`tools/build-context-pack.mjs\`${FULL ? ' --full' : ''}${ONLY ? ` --only ${ONLY.join(',')}` : ''}`);
say();
say('Everything below describes one real person. Do not invent facts to fill gaps in it —');
say('unresolved items are listed explicitly and should be asked about, not guessed.');
say();
say('---');
say();

/* ------------------------------------------------------------- core context */

const CORE = [
  'AGENTS.md',
  'profile/00-who-i-am.md',
  'profile/01-how-i-work.md',
  'profile/02-tech-environment.md',
  'profile/03-domain-knowledge.md',
  'profile/05-open-questions.md',
  'work-history/timeline.md',
  'lessons/README.md',
];

for (const f of CORE) {
  if (!existsSync(join(ROOT, f))) continue;
  say(`<!-- ===== ${f} ===== -->`);
  say();
  say(read(f));
  say();
  say('---');
  say();
}

/* ----------------------------------------------------------- project files */

const projDir = join(ROOT, 'work-history', 'projects');
if (existsSync(projDir)) {
  say('# Projects');
  say();
  for (const f of readdirSync(projDir).sort()) {
    say(`<!-- ===== work-history/projects/${f} ===== -->`);
    say();
    say(readFileSync(join(projDir, f), 'utf8').trim());
    say();
    say('---');
    say();
  }
}

/* ------------------------------------------------------------------ skills */

const manifest = JSON.parse(read('skills/manifest.json'));
const scoresPath = join(ROOT, 'ratings', 'scores.json');
const scores = existsSync(scoresPath)
  ? Object.fromEntries(JSON.parse(readFileSync(scoresPath, 'utf8')).rows.map(r => [r.name, r.total]))
  : {};

say('# Skills');
say();
say('| Skill | Type | Score /100 | What it does |');
say('|---|---|---|---|');
for (const s of manifest.skills) {
  say(`| \`${s.name}\` | ${s.type} | ${scores[s.name] ?? '—'} | ${s.summary} |`);
}
say();
say('Scores are computed by `tools/score-skills.mjs` against `ratings/RUBRIC.md`. Mean 69.3, range 44–89.');
say();

const wanted = ONLY ?? (FULL ? manifest.skills.map(s => s.name) : []);
if (wanted.length) {
  say('---');
  say();
  for (const name of wanted) {
    const p = join(ROOT, 'skills', name, 'SKILL.md');
    if (!existsSync(p)) { say(`<!-- skill not found: ${name} -->`); continue; }
    say(`<!-- ===== skills/${name}/SKILL.md ===== -->`);
    say();
    say(readFileSync(p, 'utf8').trim());
    say();

    // note any reference files without inlining them (they can be large)
    for (const sub of ['references', 'reference', 'scripts']) {
      const d = join(ROOT, 'skills', name, sub);
      if (!existsSync(d)) continue;
      const files = readdirSync(d).map(f => `skills/${name}/${sub}/${f}`);
      say(`> Additional files not inlined here: ${files.map(f => `\`${f}\``).join(', ')}`);
      say();
    }
    say('---');
    say();
  }
} else {
  say('> Skill bodies omitted. Re-run with `--full` to inline all of them,');
  say('> or `--only name1,name2` for specific ones.');
  say();
}

/* ------------------------------------------------------------------ footer */

const words = out.join('\n').split(/\s+/).length;
say('---');
say();
say(`*End of context pack. ~${words.toLocaleString()} words, roughly ${Math.round(words * 1.35 / 1000)}k tokens.*`);

process.stdout.write(out.join('\n') + '\n');
